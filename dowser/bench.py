def freeze_price_source(directory):
    import urllib.request

    price_doc = (
        urllib.request.urlopen("https://docs.typesafe.ai/models.md", timeout=15)
        .read()
        .decode()
    )
    if (
        "0.042" not in price_doc
        or "64k tokens per request" not in price_doc
        or "Output tokens are free" not in price_doc
    ):
        raise ValueError(
            "current price/ceiling differs; update accounting before paid execution"
        )
    (directory / "pricing-source.md").write_text(price_doc)
    return file_hash(directory / "pricing-source.md")


def archive_sources(directory, base, hashes):
    for relative, sha in hashes.items():
        original = base / relative
        if file_hash(original) != sha:
            raise ValueError("source changed before archival")
        archived = directory / "source" / relative
        archived.parent.mkdir(parents=True, exist_ok=True)
        archived.write_bytes(original.read_bytes())
        if file_hash(archived) != sha:
            raise ValueError("source changed during archival")


