def transient_full_failure(row):
    detail = row.get("failure", {})
    status = detail.get("http_status", 0)
    if row.get("category") == "provider" and detail.get("code") in {
        "provider_deadline",
        "deadline_exceeded",
        "request_cancelled",
    }:
        return True
    return (
        row.get("category") == "provider"
        and detail.get("retryable", False)
        and (
            detail.get("category") == "transport"
            or status in {408, 429}
            or 500 <= status < 600
        )
    )


def normalize_report_row(row):
    """Correct old trim/escalation labels without rewriting paid trial records."""
    if (
        row.get("category") == "context"
        and (row.get("terminal") or {}).get("reason") == "Jev selected escalation"
        and not row.get("failure")
        and not row.get("error_type")
    ):
        return {**row, "recorded_category": "context", "category": "abandoned"}
    return row


def runner_execution_fingerprint(source):
    """Only batch management and reporting can change on an approved resume."""
    management = {
        "run_campaign",
        "main",
        "report",
        "transient_full_failure",
        "runner_execution_fingerprint",
        "record_runner_update",
        "failure_category",
        "normalize_report_row",
    }
    nodes = []
    for node in ast.parse(source).body:
        if (
            isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
            and node.name in management
        ):
            continue
        if isinstance(node, ast.Import) and all(
            alias.name == "ast" for alias in node.names
        ):
            continue
        nodes.append(ast.dump(node, include_attributes=False))
    return fingerprint(nodes)


def record_runner_update(campaign, existing, expected, base, authorized):
    before, after = existing["code_hashes"], expected["code_hashes"]
    if set(before) != set(after) or any(
        before[k] != after[k] for k in before if k != "dowser/bench.py"
    ):
        raise ValueError("execution code changed; new campaign required")
    revisions = existing.get("runner_revisions", [])
    if revisions and revisions[-1]["sha256"] == after["dowser/bench.py"]:
        return
    if not authorized:
        raise ValueError("runner update must be explicitly recorded on resume")
    original = confined(campaign, "source/dowser/bench.py")
    current = base / "dowser/bench.py"
    if file_hash(original) != before["dowser/bench.py"] or runner_execution_fingerprint(
        original.read_text()
    ) != runner_execution_fingerprint(current.read_text()):
        raise ValueError("per-trial execution changed; new campaign required")
    source = campaign / "runner-revisions" / (after["dowser/bench.py"] + ".py")
    source.parent.mkdir(parents=True, exist_ok=True)
    source.write_bytes(current.read_bytes())
    revisions.append(
        {
            "recorded_at": datetime.now(UTC).isoformat(),
            "sha256": after["dowser/bench.py"],
            "source": str(source),
            "reason": "Batch management or reporting correction without replay; per-trial execution, scoring, configuration and budgets are unchanged. Completed paid trial records are reused.",
        }
    )
    existing["runner_revisions"] = revisions
    existing["batch_policy"] = {
        "continue_transient_full_failures": True,
        "continue_transient_pilot_failures": True,
        "cooldown_seconds": 60,
    }
    note = "Exhausted transient upstream failures in full-run trials retain zero scores and all spending reservations; the batch continues after a 60-second cooldown without replay. Other technical failures still halt."
    if note not in existing["methodological_differences"]:
        existing["methodological_differences"].append(note)
    pilot_note = "User-authorized pilot continuation retains exhausted transient provider failures with zero score and advances after a 60-second cooldown without replay. Permanent provider, schema and execution failures still halt. Full-run admission remains separately gated."
    if pilot_note not in existing["methodological_differences"]:
        existing["methodological_differences"].append(pilot_note)
    atomic_json(campaign / "manifest.json", existing)


def read_json(path):
    return json.loads(confined(Path(path).parent, Path(path).name).read_text())


def download(dataset):
    from huggingface_hub import HfApi, snapshot_download

    dataset = Path(dataset).absolute()
    if dataset.is_symlink():
        raise ValueError("dataset symlink forbidden")
    files = HfApi(token=False).list_repo_files(
        REPO, repo_type="dataset", revision=REVISION
    )
    snapshot_download(
        REPO,
        repo_type="dataset",
        revision=REVISION,
        local_dir=dataset,
        token=False,
        max_workers=4,
    )
    atomic_json(
        dataset / ".dowser-download.json",
        {"repository": REPO, "revision": REVISION, "files": sorted(files)},
    )
    print(f"Downloaded {len(files)} files at {REVISION}", flush=True)


def prepare(dataset, root, source_indexes=None):
    import yaml

    dataset, root = Path(dataset).absolute(), Path(root).absolute()
    receipt = read_json(dataset / ".dowser-download.json")
    if receipt["revision"] != REVISION or receipt["repository"] != REPO:
        raise ValueError("dataset revision mismatch")
    # Require every remotely enumerated file before indexing or paid calls.
    hashes = {}
    for relative in receipt["files"]:
        path = confined(dataset, relative)
        hashes[relative] = file_hash(path)
        path.chmod(0o444)
    scenarios = sorted(
        {
            int(p.split("/")[1].removeprefix("Scenario-"))
            for p in hashes
            if p.startswith("sre/Scenario-")
        }
    )
    if len(scenarios) != 40 or not set(PILOT) <= set(scenarios):
        raise ValueError("expected 40 public scenarios and fixed pilot")
    license_text = confined(dataset, "README.md").read_text()
    if "cc-by-4.0" not in license_text:
        raise ValueError("dataset license not verified")
    indexes = {}
    for scenario in scenarios:
        name = f"Scenario-{scenario}"
        gt = yaml.safe_load(
            confined(dataset, f"sre/{name}/ground_truth.yaml").read_text()
        )
        score(gt, {"contributing_factors": []}, [])  # validate both GT layouts
        output = root / "indexes" / f"{name}.sqlite3"
        expected = {
            p.removeprefix(f"sre/{name}/"): h
            for p, h in hashes.items()
            if p.startswith(f"sre/{name}/")
        }
        if output.exists():
            index = EvidenceIndex(output, scenario)
            if any(expected.get(p) != h for p, h in index.meta["files"].items()):
                raise ValueError("existing index differs from dataset")
            meta = index.meta
            coverage = {
                relative for _, relative, _ in snapshot_files(dataset / "sre" / name)
            }
            if set(meta["files"]) != coverage or meta["version"] != 2:
                raise ValueError(
                    "existing index has old coverage or schema; prepare in a separate root"
                )
        else:
            if source_indexes is not None:
                evidence_files = {
                    relative
                    for _, relative, _ in snapshot_files(dataset / "sre" / name)
                }
                meta = upgrade_index(
                    confined(Path(source_indexes), f"{name}.sqlite3"),
                    output,
                    scenario,
                    {k: v for k, v in expected.items() if k in evidence_files},
                )
            else:
                meta = create_index(dataset / "sre" / name, output, scenario)
            output.chmod(0o444)
        indexes[name] = {**meta, "path": str(output), "sha256": file_hash(output)}
        print(f"Prepared {name}: {meta['counts']}", flush=True)
    metadata = {
        "repository": REPO,
        "revision": REVISION,
        "license": "CC-BY-4.0",
        "dataset": str(dataset),
        "files": hashes,
        "scenarios": scenarios,
        "indexes": indexes,
    }
    metadata["fingerprint"] = fingerprint(metadata)
    atomic_json(root / "prepared.json", metadata)
    return metadata


def code_metadata(base):
    paths = [
        *base.glob("dowser/*.py"),
        *base.glob("plugins/*.py"),
        base / "pyproject.toml",
    ]
    return {p.relative_to(base).as_posix(): file_hash(p) for p in sorted(paths)}


