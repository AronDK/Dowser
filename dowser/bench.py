        "",
        f"Dataset revision: `{manifest['dataset_revision']}`; license: {manifest['dataset_license']}; Python: {manifest['python']}; lock SHA-256: `{manifest['dependency_lock_sha256']}`.",
        "",
        "All dataset and code hashes, configuration, price, and methodological differences are in `manifest.json`. Individual histories are in `history.sqlite3`; submissions, scoring, trial records, and the durable spending ledger are adjacent. Results are exported as `results.jsonl` and `results.csv`.",
